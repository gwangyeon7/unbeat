export type Playlist = {
  id: number;
  name: string;
  createdAt: string;
  trackCount: number;
  isAutoGenerated: boolean;
  isPublic: boolean;
};

// (게이미피케이션 2단계, 2.5단계에서 ownerNickname 추가) 다른 사용자가 공개한 재생목록
// 둘러보기 피드용. ownerNickname이 null인 건 닉네임 도입 이전에 이미 공개로 전환됐던
// 레코드뿐이라 사실상 과거 데이터 방어용 — 프론트에서 "익명"으로 표시.
export type PublicPlaylist = {
  id: number;
  name: string;
  createdAt: string;
  trackCount: number;
  ownerNickname: string | null;
  // (랭킹 피드 매거진형 카드, 2026-10-10) 담긴 곡 중 이미지가 있는 가장 최근 곡의 커버 —
  // 곡이 없거나 전부 이미지가 없으면 null(프론트가 단색 플레이스홀더로 대체).
  coverImageUrl: string | null;
  // (게이미피케이션 3단계) 등수 배지(금/은/동)는 "짜치다"는 반응으로 빼고 좋아요 숫자만 남김 —
  // 피드 자체가 likeCount 내림차순으로 정렬돼 내려오므로, 카드가 나열된 순서가 곧 랭킹.
  likeCount: number;
  likedByMe: boolean;
  // (랭킹 카테고리 필터, 2026-10-10 추가) lib/categories.ts의 value 중 하나 — 카테고리 도입
  // 이전에 이미 공개됐던 재생목록은 null일 수 있음.
  category: string | null;
};

