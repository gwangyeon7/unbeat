// (게이미피케이션 3단계) 좋아요 — 로그인 필수. 비로그인 상태로 호출하면 403(PlaylistApiError,
// status===403)이 그대로 던져지므로, 호출하는 쪽이 공개 전환과 같은 패턴으로 로그인 모달을 띄움.
