// (게이미피케이션 2단계, 카테고리 필터에서 category 파라미터 추가) 공개/비공개 전환 — 로그인
// 안 한 상태로 공개(true) 요청하면 백엔드가 403, 닉네임 없으면 428, 카테고리 없으면/잘못되면
// 400을 돌려줌(playlistFetch의 !res.ok 체크로 PlaylistApiError가 그대로 던져짐, 호출하는
// 쪽에서 status로 구분해 안내). category는 isPublic=false(비공개 전환)일 땐 안 보내도 됨.
export function setPlaylistVisibility(
  id: number,
  isPublic: boolean,
  category?: string
): Promise<Playlist> {
  return playlistFetch<Playlist>(`/playlists/${id}/visibility`, {
    method: "PATCH",
    body: JSON.stringify({ isPublic, category }),
  });
}

