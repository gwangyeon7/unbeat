package com.unbeat.playlist.userplaylist

import org.springframework.data.jpa.repository.JpaRepository

interface PlaylistRepository : JpaRepository<Playlist, Long> {
    fun findBySessionIdOrderByCreatedAtDesc(sessionId: String): List<Playlist>
    fun findBySessionIdAndIsAutoGenerated(sessionId: String, isAutoGenerated: Boolean): List<Playlist>

    // (게이미피케이션 2단계) "다른 사용자 재생목록 둘러보기" 피드용. 페이지네이션은 MVP 범위 밖이라
    // 최신 N개만 잘라서 봄(서비스 레이어에서 limit) — 공개 재생목록이 많아지면 나중에 보강 필요.
    fun findByIsPublicTrueOrderByCreatedAtDesc(): List<Playlist>

    // (2.5단계) 프로필 페이지용 — 특정 사용자(닉네임)가 공개한 재생목록만.
    fun findByUserIdAndIsPublicTrueOrderByCreatedAtDesc(userId: String): List<Playlist>
}
