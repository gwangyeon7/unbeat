package com.unbeat.playlist.userplaylist

import com.unbeat.playlist.favoritetrack.FavoriteTrackRepository
import com.unbeat.playlist.userplaylist.dto.AutoMixTrack
import com.unbeat.playlist.userplaylist.dto.PlaylistResponse
import org.springframework.stereotype.Service
import org.springframework.transaction.annotation.Transactional
import java.time.format.DateTimeFormatter

/**
 * 즐겨찾기한 곡을 무작위로 섞어서 "오늘의 믹스" 재생목록 1개를 만든다.
 *
 * 원래는 Last.fm 태그로 장르를 나눠 장르별 재생목록을 만들었는데, 태그가 비어 있거나(조회 실패 등)
 * 장르별로 2곡이 안 모이는 곡이 절반 가까이 돼서 결과가 빈약했음 — 그래서 "누를 때마다 즐겨찾기에서
 * 새로 골라 섞어주는 믹스 하나"로 단순화함.
 *
 * 지금은 프론트가 즐겨찾기 + 비슷한 곡 + 즐겨찾기 아티스트 인기곡(즐겨찾기가 없으면 인기 차트)으로
 * 후보를 모아 곡을 고른 뒤 createMix(POST /playlists/auto-mix)로 저장만 맡기는 게 기본 경로이고,
 * generate(즐겨찾기만 섞기)는 후보 조회가 전부 실패했을 때의 폴백으로 남겨둠.
 *
 * PlaylistService(수동 CRUD)와 분리한 이유: 이 클래스만 FavoriteTrackRepository를 갖다 써서
 * "즐겨찾기 도메인을 읽어서 재생목록 도메인에 쓰는" 교차 로직을 한곳에 모아두기 위함 — 수동 CRUD는
 * 즐겨찾기를 몰라도 되는데, 여길 합쳐두면 그 경계가 흐려짐.
 */
@Service
class AutoPlaylistService(
    private val favoriteTrackRepository: FavoriteTrackRepository,
    private val playlistRepository: PlaylistRepository,
    private val playlistTrackRepository: PlaylistTrackRepository
) {

    /**
     * 즐겨찾기를 섞어서 최대 MIX_SIZE곡을 담은 "오늘의 믹스"를 만듦 — 누를 때마다 구성/순서가 달라짐.
     * 버튼을 다시 눌러도 중복이 쌓이지 않도록 이전 자동 재생목록(예전 장르별 재생목록 포함)은 지우고
     * 새로 만듦 — 수동으로 만든 재생목록(isAutoGenerated=false)은 건드리지 않음.
     */
    @Transactional
    fun generate(sessionId: String): List<PlaylistResponse> {
        val favorites = favoriteTrackRepository.findBySessionIdOrderByCreatedAtDesc(sessionId)

        // 즐겨찾기가 없으면 아무것도 안 만들고 기존 자동 재생목록도 그대로 둠 —
        // 빈 목록을 받으면 프론트가 "즐겨찾기한 곡이 있어야 만들어져요" 안내를 보여줌.
        if (favorites.isEmpty()) return emptyList()

        val mixTracks = favorites.shuffled().take(MIX_SIZE).map {
            AutoMixTrack(artistName = it.artistName, trackName = it.trackName, url = it.url, imageUrl = it.imageUrl)
        }
        return listOf(replaceWithMix(sessionId, mixTracks))
    }

    /**
     * 프론트가 고른 곡으로 "오늘의 믹스"를 저장(POST /playlists/auto-mix). 곡 수/필드 검증은 컨트롤러에서 함.
     * 같은 재생목록에 같은 곡이 두 번 들어가면 (playlist_id, artist_name, track_name) 유니크 제약에
     * 걸리므로, 프론트가 중복을 걸렀더라도 여기서 한 번 더 걸러냄.
     */
    @Transactional
    fun createMix(sessionId: String, tracks: List<AutoMixTrack>): PlaylistResponse {
        val distinct = tracks.distinctBy { it.artistName.trim().lowercase() to it.trackName.trim().lowercase() }
        return replaceWithMix(sessionId, distinct)
    }

    // 이전 자동 재생목록을 지우고 "오늘의 믹스"를 새로 만들어 곡을 넣음 — generate/createMix 공통
    private fun replaceWithMix(sessionId: String, tracks: List<AutoMixTrack>): PlaylistResponse {
        val previousAuto = playlistRepository.findBySessionIdAndIsAutoGenerated(sessionId, true)
        previousAuto.forEach { playlistTrackRepository.deleteByPlaylistId(it.id!!) }
        playlistRepository.deleteAll(previousAuto)

        val playlist = playlistRepository.save(
            Playlist(sessionId = sessionId, name = MIX_NAME, isAutoGenerated = true)
        )
        tracks.forEach { track ->
            playlistTrackRepository.save(
                PlaylistTrack(
                    playlistId = playlist.id!!,
                    artistName = track.artistName.trim(),
                    trackName = track.trackName.trim(),
                    url = track.url,
                    imageUrl = track.imageUrl
                )
            )
        }
        return PlaylistResponse(
            id = playlist.id!!,
            name = playlist.name,
            createdAt = playlist.createdAt.format(DateTimeFormatter.ISO_LOCAL_DATE_TIME),
            trackCount = tracks.size,
            isAutoGenerated = true,
            isPublic = playlist.isPublic,
            coverImageUrl = playlistTrackRepository
                .findFirstByPlaylistIdAndImageUrlIsNotNullOrderByAddedAtDesc(playlist.id!!)?.imageUrl
        )
    }

    companion object {
        private const val MIX_NAME = "오늘의 믹스"
        private const val MIX_SIZE = 20
    }
}
