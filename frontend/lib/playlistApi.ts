// "즐겨찾기해놓고 오래 안 들은 곡"을 찾아줌 — "지워도 될까요?"라고 먼저 물어보는 정리 기능용.
// 기본 6개월. 무작정 지우지 않고 후보만 반환하며, 실제 삭제는 사용자가 고른 것만
// removeFavoriteTrack을 개별 호출해서 처리함.
export function getStaleFavoriteTracks(months = 6): Promise<FavoriteTrack[]> {
  return playlistFetch<FavoriteTrack[]>(`/favorite-tracks/stale?months=${months}`);
}

// 즐겨찾기(별표)와는 별개 도메인 — 별표는 "이 곡 좋다"는 빠른 표시고, 재생목록은
// 사용자가 이름을 직접 정해서 곡을 골라 담는 것(유튜브 뮤직 사이드바 "새 재생목록"과 같은 개념).
export type Playlist = {
  id: number;
  name: string;
  createdAt: string;
  trackCount: number;
  isAutoGenerated: boolean;
};

export type PlaylistTrack = {
  id: number;
  artistName: string;
  trackName: string;
  url: string | null;
  imageUrl: string | null;
  addedAt: string;
};

export function getPlaylists(): Promise<Playlist[]> {
  return playlistFetch<Playlist[]>("/playlists");
}

export function createPlaylist(name: string): Promise<Playlist> {
  return playlistFetch<Playlist>("/playlists", {
    method: "POST",
    body: JSON.stringify({ name }),
  });
}

export function deletePlaylist(id: number): Promise<void> {
  return playlistFetch<void>(`/playlists/${id}`, { method: "DELETE" });
}

export function getPlaylistTracks(playlistId: number): Promise<PlaylistTrack[]> {
  return playlistFetch<PlaylistTrack[]>(`/playlists/${playlistId}/tracks`);
}

export function addTrackToPlaylist(
  playlistId: number,
  artistName: string,
  trackName: string,
  trackUrl: string | null,
  imageUrl: string | null
): Promise<PlaylistTrack> {
  return playlistFetch<PlaylistTrack>(`/playlists/${playlistId}/tracks`, {
    method: "POST",
    body: JSON.stringify({ artistName, trackName, trackUrl, imageUrl }),
  });
}

export function removeTrackFromPlaylist(playlistId: number, trackId: number): Promise<void> {
  return playlistFetch<void>(`/playlists/${playlistId}/tracks/${trackId}`, { method: "DELETE" });
}

