// 좋겠다"는 피드백으로 추가. 즐겨찾기한 곡의 Last.fm 태그를 서버에서 분석해서 장르별 재생목록을
// 통째로 만들어줌 — 다시 눌러도 이전 자동 생성 결과를 지우고 최신 즐겨찾기 기준으로 재생성함.
export function generateAutoPlaylists(): Promise<Playlist[]> {
  return playlistFetch<Playlist[]>("/playlists/auto-generate", { method: "POST" });
}
